import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const html=readFileSync('web/dist/index.html','utf8');
if(/<script[^>]+src=|<link[^>]+rel="stylesheet"/.test(html))throw Error('Web interface must be self-contained');
if(/SUPABASE_SERVICE_ROLE_KEY|sb_secret_|BEGIN PRIVATE KEY/.test(html))throw Error('Private key in web bundle');
mkdirSync('src/generated',{recursive:true});
writeFileSync('src/generated/pwa.ts','// Generated by npm run build:web. Do not edit.\nexport default '+JSON.stringify(html)+';\n');
console.log('Embedded Connect PWA: '+Buffer.byteLength(html)+' bytes');
